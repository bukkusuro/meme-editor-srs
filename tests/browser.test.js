'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const http = require('node:http');
const { chromium } = require('playwright-core');
const { PNG } = require('pngjs');
const root = path.resolve(__dirname, '..');
const chrome = [process.env.CHROME_PATH, '/usr/bin/google-chrome', '/usr/bin/chromium', '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'].filter(Boolean).find((p) => fs.existsSync(p));

test('editor supports layers, image loading, history and PNG on a narrow screen', { timeout: 120000 }, async (t) => {
  assert.ok(chrome, 'Set CHROME_PATH to a Chrome or Chromium executable');
  const server = http.createServer((req, res) => {
    const url = new URL(req.url, 'http://127.0.0.1');
    const file = path.resolve(root, '.' + (url.pathname === '/' ? '/index.html' : url.pathname));
    if (!file.startsWith(root + path.sep)) { res.writeHead(403).end(); return; }
    const types = { '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css' };
    fs.readFile(file, (err, data) => err ? res.writeHead(404).end() : res.writeHead(200, { 'Content-Type': types[path.extname(file)] || 'application/octet-stream' }).end(data));
  });
  await new Promise((resolve) => server.listen(0, '127.0.0.1', resolve));
  t.after(() => server.close());
  const origin = `http://127.0.0.1:${server.address().port}`;
  const browser = await chromium.launch({ executablePath: chrome, headless: true, args: ['--no-sandbox'] });
  t.after(() => browser.close());
  const context = await browser.newContext({ viewport: { width: 320, height: 800 }, acceptDownloads: true });
  const page = await context.newPage();
  const external = [];
  page.on('request', (req) => { if (!req.url().startsWith(origin) && !req.url().startsWith('blob:')) external.push(req.url()); });
  await page.goto(origin);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  const add = page.getByRole('button', { name: 'Добавить текст' });
  await add.click(); await page.locator('#text-content').fill('Привет!\nМир');
  for (let i = 0; i < 4; i++) await add.click();
  assert.equal(await page.locator('#objects option').count(), 5);
  await page.locator('#objects').selectOption('1');
  assert.equal(await page.locator('#text-content').inputValue(), 'Привет!\nМир');
  const xBefore = await page.evaluate(() => scene.texts.find((item) => item.id === 1).x);
  await page.locator('#canvas').focus();
  await page.keyboard.press('ArrowRight');
  assert.equal(await page.evaluate(() => scene.texts.find((item) => item.id === 1).x), xBefore + 1);
  await page.locator('#text-content').focus();
  await page.keyboard.press('ArrowRight');
  assert.equal(await page.evaluate(() => scene.texts.find((item) => item.id === 1).x), xBefore + 1);
  await page.locator('#canvas').scrollIntoViewIfNeeded();
  const rect = await page.locator('#canvas').boundingBox();
  const sx = rect.x + rect.width * (xBefore + 1) / 1200;
  const sy = rect.y + rect.height * 100 / 1200;
  await page.mouse.move(sx, sy); await page.mouse.down(); await page.mouse.move(sx + 12, sy + 8); await page.mouse.up();
  assert.ok(await page.evaluate(() => scene.texts.find((item) => item.id === 1).x) > xBefore + 1);
  await page.locator('#send-back').click();
  await page.getByRole('button', { name: 'Отменить' }).click();
  await page.getByRole('button', { name: 'Повторить' }).click();
  const image = await page.evaluate(() => { const c = document.createElement('canvas'); c.width = 320; c.height = 180; const ctx = c.getContext('2d'); ctx.fillStyle = '#339966'; ctx.fillRect(0, 0, 320, 180); return c.toDataURL('image/png').split(',')[1]; });
  await page.locator('#image-file').setInputFiles({ name: 'photo.png', mimeType: 'image/png', buffer: Buffer.from(image, 'base64') });
  await page.waitForFunction(() => document.querySelector('#canvas').width === 320);
  assert.equal(await page.locator('#objects option').count(), 5);
  for (const type of ['image/jpeg', 'image/webp']) {
    const encoded = await page.evaluate((mime) => { const c = document.createElement('canvas'); c.width = 240; c.height = 400; c.getContext('2d').fillRect(0, 0, 240, 400); return c.toDataURL(mime).split(',')[1]; }, type);
    await page.locator('#image-file').setInputFiles({ name: type === 'image/jpeg' ? 'photo.jpg' : 'photo.webp', mimeType: type, buffer: Buffer.from(encoded, 'base64') });
    await page.waitForFunction(() => document.querySelector('#canvas').width === 240);
    assert.equal(await page.locator('#canvas').evaluate((c) => c.height), 400);
  }
  await page.locator('#image-file').setInputFiles({ name: 'photo.png', mimeType: 'image/png', buffer: Buffer.from(image, 'base64') });
  await page.waitForFunction(() => document.querySelector('#canvas').width === 320);
  await page.locator('#image-file').setInputFiles({ name: 'broken.png', mimeType: 'image/png', buffer: Buffer.from('not a picture') });
  await page.getByText('Не удалось прочитать изображение. Выберите другой файл.').waitFor();
  assert.equal(await page.locator('#canvas').evaluate((c) => c.width), 320);
  await add.click();
  await page.locator('#text-content').fill('MEME');
  await page.locator('#text-color').fill('#000000');
  await page.locator('#image-file').setInputFiles({ name: 'bad.txt', mimeType: 'text/plain', buffer: Buffer.from('bad') });
  assert.match(await page.locator('#message').innerText(), /PNG/);
  assert.equal(await page.locator('#canvas').evaluate((el) => el.width), 320);
  await page.locator('#image-file').setInputFiles({ name: 'large.png', mimeType: 'image/png', buffer: Buffer.alloc(10000001) });
  assert.match(await page.locator('#message').innerText(), /10 МБ/);
  assert.equal(await page.locator('#objects option').count(), 6);
  const previewHasMarker = await page.locator('#canvas').evaluate((canvas) => { const pixels = canvas.getContext('2d').getImageData(0, 0, canvas.width, canvas.height).data; for (let i = 0; i < pixels.length; i += 4) if (pixels[i] === 228 && pixels[i + 1] === 91 && pixels[i + 2] === 75) return true; return false; });
  assert.equal(previewHasMarker, true);
  const event = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Скачать мем' }).click();
  const download = await event;
  assert.equal(download.suggestedFilename(), 'meme.png');
  const png = PNG.sync.read(fs.readFileSync(await download.path()));
  assert.deepEqual([png.width, png.height], [320, 180]);
  const exportHasMarker = png.data.some((value, i) => i % 4 === 0 && value === 228 && png.data[i + 1] === 91 && png.data[i + 2] === 75);
  assert.equal(exportHasMarker, false);
  page.once('dialog', (dialog) => dialog.accept());
  await page.getByRole('button', { name: 'Новый проект' }).click();
  assert.equal(await page.locator('#canvas').evaluate((el) => el.width), 1200);
  assert.equal(await page.locator('#undo').isDisabled(), true);
  for (let i = 0; i < 20; i++) await add.click();
  for (let i = 0; i < 20; i++) await page.getByRole('button', { name: 'Отменить' }).click();
  assert.equal(await page.locator('#objects').isDisabled(), true);
  for (let i = 0; i < 20; i++) await page.getByRole('button', { name: 'Повторить' }).click();
  assert.equal(await page.locator('#objects option').count(), 20);
  assert.deepEqual(external, []);
});
